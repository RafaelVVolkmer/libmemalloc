--- Validate cache settings before producing runner outputs or files.
-- @return table: pure policy functions and the required environment keys.
local function CACHE_PLANE_loadModule()
   local exports = {}
   local CACHE_PLANE_TIMEOUT = "30s"
   local CACHE_PLANE_PREFIX = "libmemalloc/cache"
   local CACHE_PLANE_MODES =
      { disabled = true, optional = true, required = true }

   exports.environment = {
      "INPUT_MODE",
      "EVENT_NAME",
      "REF_NAME",
      "DEFAULT_BRANCH",
      "LIBMEMALLOC_CACHE_ROOT",
      "LIBMEMALLOC_CI_CACHE_PLANE_MODE",
      "LIBMEMALLOC_CI_OCI_REGISTRY",
      "LIBMEMALLOC_CI_BAZEL_REMOTE_CACHE",
      "LIBMEMALLOC_CI_BAZEL_REMOTE_INSTANCE",
      "LIBMEMALLOC_CI_TOOL_CACHE_DIR",
      "LIBMEMALLOC_CI_S3_CACHE_BUCKET",
      "LIBMEMALLOC_CI_S3_CACHE_ENDPOINT",
      "LIBMEMALLOC_CI_S3_CACHE_PREFIX",
      "HTTPS_PROXY",
      "https_proxy",
      "HTTP_PROXY",
      "http_proxy",
   }

   --- Read a setting without allowing control bytes into runner protocols.
   -- @param cog table: explicit environment settings.
   -- @param name string: key to resolve.
   -- @param fallback string|nil: value used for absent or empty settings.
   -- @return string: validated setting.
   local function cache_plane_value(cog, name, fallback)
      local value = cog[name] or ""

      assert(type(value) == "string", "cache setting must be text: " .. name)
      assert(not value:find("%c"), "control byte in cache setting: " .. name)
      if value == "" then
         value = fallback or ""
      end

      return value
   end

   --- Restrict cache origins to TLS or literal loopback plaintext endpoints.
   -- @param value string: configured endpoint; empty disables the service.
   -- @param grpc boolean: whether Bazel's gRPC schemes are accepted.
   -- @return nil: invalid endpoints raise before side effects.
   local function cache_plane_endpoint(value, grpc)
      local tls = value:match("^https://[^%s]+$")
         or (grpc and value:match("^grpcs://[^%s]+$"))
      local scheme, host = value:match("^(%a+)://([^/]+)/*$")
      local loopback = host
         and (host:match("^localhost:%d+$") or host:match("^127%.0%.0%.1:%d+$"))
      local plain = scheme == "http" or (grpc and scheme == "grpc")

      assert(
         value == "" or tls or (plain and loopback),
         "cache endpoint requires TLS or a literal loopback origin"
      )
   end

   --- Validate object store settings, including the non-traversing prefix.
   -- @param cog table: explicit environment settings.
   -- @param has_aws boolean: whether the caller found the AWS executable.
   -- @return boolean: whether a shared object store is configured.
   local function cache_plane_shared(cog, has_aws)
      local bucket = cache_plane_value(cog, "LIBMEMALLOC_CI_S3_CACHE_BUCKET")
      local endpoint =
         cache_plane_value(cog, "LIBMEMALLOC_CI_S3_CACHE_ENDPOINT")
      local prefix = cache_plane_value(
         cog,
         "LIBMEMALLOC_CI_S3_CACHE_PREFIX",
         CACHE_PLANE_PREFIX
      )

      assert(endpoint == "" or bucket ~= "", "S3 endpoint requires a bucket")
      if bucket ~= "" then
         assert(not bucket:find("[/:%s]"), "invalid S3 bucket name")
         cache_plane_endpoint(endpoint, false)
         assert(
            prefix:sub(1, 1) ~= "/" and not prefix:find("[\\%s]"),
            "invalid S3 object prefix"
         )
         for component in prefix:gmatch("[^/]+") do
            assert(component ~= "..", "S3 prefix traversal")
         end
         assert(has_aws, "shared S3 cache requires the aws CLI")
      end

      return bucket ~= ""
   end

   --- Produce the Bazel configuration from already validated settings.
   -- @param cog table: explicit environment settings.
   -- @param enabled boolean: whether the configured service is active.
   -- @param write boolean: whether the event may populate shared results.
   -- @return string: deterministic rc contents with a terminal newline.
   local function cache_plane_bazel(cog, enabled, write)
      local rows = { "# Generated by Libmemalloc CI. Do not commit." }

      if enabled then
         rows[#rows + 1] = "build --remote_cache="
            .. cog.LIBMEMALLOC_CI_BAZEL_REMOTE_CACHE
         rows[#rows + 1] = "build --remote_verify_downloads=true"
         rows[#rows + 1] = "build --remote_timeout=" .. CACHE_PLANE_TIMEOUT
         rows[#rows + 1] = "build --remote_upload_local_results="
            .. tostring(write)
         local instance =
            cache_plane_value(cog, "LIBMEMALLOC_CI_BAZEL_REMOTE_INSTANCE")

         if instance ~= "" then
            rows[#rows + 1] = "build --remote_instance_name=" .. instance
         end
      end

      return table.concat(rows, "\n") .. "\n"
   end

   --- Determine whether at least one validated service is configured.
   -- @param flags table: ordered boolean service states.
   -- @return boolean: whether any service is available.
   local function cache_plane_hasService(flags)
      local enabled = false

      for _, value in ipairs(flags) do
         enabled = enabled or value
      end

      return enabled
   end

   --- Restrict shared writes to trusted default-branch events.
   -- @param cog table: explicit event and branch settings.
   -- @param active boolean: whether caching is enabled by policy.
   -- @return boolean: whether the event has cache write authority.
   local function cache_plane_canWrite(cog, active)
      local branch = cache_plane_value(cog, "DEFAULT_BRANCH")

      return active
         and branch ~= ""
         and cache_plane_value(cog, "REF_NAME") == branch
         and (cog.EVENT_NAME == "push" or cog.EVENT_NAME == "workflow_dispatch")
   end

   --- Resolve service state and write authority without logging endpoints.
   -- @param cog table: environment captured by the entrypoint.
   -- @param has_aws boolean: whether the AWS client is available.
   -- @return table: validated output fields and Bazel rc contents.
   local function CACHE_PLANE_resolve(cog, has_aws)
      for _, name in ipairs(exports.environment) do
         cache_plane_value(cog, name)
      end

      local mode = cache_plane_value(
         cog,
         "INPUT_MODE",
         cache_plane_value(cog, "LIBMEMALLOC_CI_CACHE_PLANE_MODE", "optional")
      )
      local root = cache_plane_value(cog, "LIBMEMALLOC_CACHE_ROOT")
      local registry = cache_plane_value(cog, "LIBMEMALLOC_CI_OCI_REGISTRY")
      local bazel = cache_plane_value(cog, "LIBMEMALLOC_CI_BAZEL_REMOTE_CACHE")
      local instance =
         cache_plane_value(cog, "LIBMEMALLOC_CI_BAZEL_REMOTE_INSTANCE")
      local local_tools =
         cache_plane_value(cog, "LIBMEMALLOC_CI_TOOL_CACHE_DIR")

      assert(CACHE_PLANE_MODES[mode], "invalid cache-plane mode")
      assert(root:sub(1, 1) == "/", "cache root must be absolute")
      assert(not registry:find("[/%s]"), "OCI registry must be a host[:port]")
      assert(
         not bazel:find("%s") and not instance:find("%s"),
         "whitespace in Bazel settings"
      )
      assert(
         local_tools == "" or local_tools:sub(1, 1) == "/",
         "tool cache must be absolute"
      )
      cache_plane_endpoint(bazel, true)

      local shared = cache_plane_shared(cog, has_aws)
      local active = mode ~= "disabled"
      local write = cache_plane_canWrite(cog, active)
      local proxy = cache_plane_value(
         cog,
         "HTTPS_PROXY",
         cache_plane_value(
            cog,
            "https_proxy",
            cache_plane_value(
               cog,
               "HTTP_PROXY",
               cache_plane_value(cog, "http_proxy")
            )
         )
      ) ~= ""

      assert(
         mode ~= "required" or shared,
         "required cache plane is missing the shared S3 cache"
      )

      return {
         enabled = active and cache_plane_hasService({
            proxy,
            registry ~= "",
            bazel ~= "",
            local_tools ~= "",
            shared,
         }),
         bazelrc = root .. "/tools/libmemalloc-cache-plane/bazelrc",
         bazel_write = write,
         shared_cache_enabled = shared,
         shared_cache_write = write,
         registry_enabled = registry ~= "",
         proxy_enabled = proxy,
         contents = cache_plane_bazel(cog, active and bazel ~= "", write),
         mode = mode,
      }
   end

   exports.resolve = CACHE_PLANE_resolve

   return exports
end

return CACHE_PLANE_loadModule()

